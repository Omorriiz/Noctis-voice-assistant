/** OTA-обновление: скачивание образа с сервера в неактивный слот, проверка SHA-256, откат при неудаче. */
#pragma once

#include <stdbool.h>

#include "noctis_core.h"

/** Вызывать при старте: если запущена свежая прошивка, ждёт подтверждения; без него откатывается. */
void ota_init(void);

/** Подтверждает работоспособность текущей прошивки (вызывается после успешного подключения к серверу). */
void ota_mark_valid(void);

/** Запускает обновление в отдельной задаче. false — отклонено (занято, не новее, нет ссылки на сервер). */
bool ota_start(const noctis_command_t* cmd);
