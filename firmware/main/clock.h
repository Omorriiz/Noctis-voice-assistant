/** Время без RTC: NTP (SNTP) при наличии интернета + время от сервера (time_sync) как запасной источник.
 *  Часовой пояс — смещение от UTC, которое присылает сервер (сохраняется в NVS). */
#pragma once

#include <stdbool.h>
#include <stdint.h>

/** После получения IP: запускает SNTP. Можно вызывать повторно. */
void clock_start_sntp(void);

/** Применяет сообщение time_sync {epoch, utc_offset}: смещение запоминается всегда; системное время ставится только
 *  если SNTP ещё не синхронизировался (NTP точнее, сервер — запасной вариант в сетях без выхода в интернет). */
void clock_apply_server(int64_t epoch, int32_t utc_offset);

int64_t clock_now(void);       // секунды UTC (1970 год, пока время не синхронизировано)
int32_t clock_offset(void);    // смещение местного времени от UTC, сек
bool clock_valid(void);        // время синхронизировано (не раньше 2024-01-01)
